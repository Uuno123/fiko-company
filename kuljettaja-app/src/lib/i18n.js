export function translate(language, key, params) {
  const template = STRINGS[language]?.[key] ?? STRINGS.fi[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''))
}

// Valittu kieli myös komponenttien ulkopuolisille teksteille (ilmoitukset,
// virheet, päivien nimet). useT päivittää sen jokaisella piirrolla, ja kielen
// vaihto piirtää näkymät uudelleen.
let currentLanguage = 'fi'

function setCurrentLanguage(language) {
  currentLanguage = language
}

// tr('avain', { arvot }) kirjastoissa (lib/jobs.js, lib/format.js ...).
export function tr(key, params) {
  return translate(currentLanguage, key, params)
}

// t('avain', { arvot }) nykyisellä kielellä.
export function useT() {
  const { settings } = useCourier()
  const language = settings.language === 'en' ? 'en' : 'fi'
  setCurrentLanguage(language)
  return useCallback((key, params) => translate(language, key, params), [language])
}
